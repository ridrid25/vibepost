/**
 * Сверка ботов: какой бот каким проектом управляется.
 *
 *   node scripts/сверка-ботов.mjs              — таблица на экран
 *   node scripts/сверка-ботов.mjs --markdown   — готовый блок для БОТЫ.md
 *   node scripts/сверка-ботов.mjs --проверка   — самотест, без сети и токенов
 *
 * Зачем именно такая. Упоминание бота в коде НИЧЕГО не значит: `@RidFinance_bot`
 * встречается в пяти репозиториях, но управляет им ровно один. Telegram отдаёт
 * каждое сообщение только на ОДИН вебхук, и настоящая связь «бот ↔ проект»
 * живёт не в исходниках, а вот в этом адресе. Поэтому скрипт не читает код —
 * он спрашивает у самого Telegram, куда бот сейчас шлёт апдейты, и опознаёт
 * проект по домену.
 *
 * Второй бот на том же токене молча забирает вебхук себе, и первый проект
 * становится глухим — без ошибки, без письма, просто перестаёт получать
 * сообщения. Эта сверка нужна, чтобы такое было видно за десять секунд.
 *
 * ТОКЕНЫ В РЕПОЗИТОРИЙ НЕ ПОПАДАЮТ. Скрипт берёт их из `токены.local.txt`
 * (закрыт в .gitignore) или из .env, а на экран печатает только номер бота
 * до двоеточия — хвост всегда скрыт, вывод можно пересылать без опаски.
 */
import { readFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const корень = dirname(dirname(fileURLToPath(import.meta.url)));

// ── Правила опознания: по домену вебхука понятно, кто обслуживает бота ──────
//
// Не нашли свой домен в этом списке — допишите строку сюда. Это единственное
// место, которое нужно править, когда появляется новый проект.
const ПРАВИЛА = [
  { признак: /\.supabase\.co\/functions\/v1\//i, проект: 'vibepost',                         как: 'Supabase Edge Function' },
  { признак: /script\.google\.com\/macros\//i,   проект: 'rid-finance',                      как: 'Google Apps Script' },
  { признак: /\/telegram\/webhook\b/i,           проект: 'pomoshchnik-naznacheniya-vstrech', как: 'VPS, Docker + Caddy' },
  { признак: /\bn8n\b/i,                         проект: 'data-smeta-audit',                 как: 'n8n' },
];

/** Опознать проект по адресу вебхука. Экспортируется ради самотеста. */
export function опознать(адрес) {
  if (!адрес) return { проект: '—', как: 'вебхук не задан' };
  for (const п of ПРАВИЛА) if (п.признак.test(адрес)) return { проект: п.проект, как: п.как };
  return { проект: '❓ неизвестен', как: 'допишите правило в ПРАВИЛА' };
}

/** Показать токен безопасно: номер бота — не секрет, хвост — секрет. */
export function безопасно(токен) {
  const номер = String(токен).split(':')[0];
  return /^\d{5,}$/.test(номер) ? `${номер}:…` : '???';
}

/** Собрать токены из файла или .env. Возвращает [{токен, пометка}]. */
export function разобратьТокены(текст) {
  const боты = [];
  for (const строка of String(текст).split(/\r?\n/)) {
    const чистая = строка.trim();
    if (!чистая || чистая.startsWith('#')) continue;
    // Поддерживаем и «ТОКЕН», и «ИМЯ=ТОКЕН», и «ТОКЕН  # пометка».
    const m = чистая.match(/(\d{5,}:[A-Za-z0-9_-]{20,})/);
    if (!m) continue;
    const до = чистая.slice(0, m.index).replace(/[=\s]+$/, '').trim();
    const после = чистая.slice(m.index + m[1].length).replace(/^[\s#]+/, '').trim();
    боты.push({ токен: m[1], пометка: после || до || '' });
  }
  // Один и тот же токен, вписанный дважды, сверять дважды незачем.
  const видели = new Set();
  return боты.filter(б => !видели.has(б.токен) && видели.add(б.токен));
}

// ── Самотест: гоняет логику на выдуманных данных, без сети ─────────────────
if (process.argv.includes('--проверка')) {
  let плохо = 0;
  const проба = (имя, было, ждём) => {
    const ок = JSON.stringify(было) === JSON.stringify(ждём);
    console.log(`${ок ? '  ок  ' : ' СЛОМАНО'}  ${имя}`);
    if (!ок) { console.log(`         ждали: ${JSON.stringify(ждём)}`); console.log(`         вышло: ${JSON.stringify(было)}`); плохо++; }
  };

  console.log('\nСАМОТЕСТ СВЕРКИ (сеть не нужна)\n');
  проба('Supabase → vibepost',
    опознать('https://abcdef.supabase.co/functions/v1/telegram-webhook').проект, 'vibepost');
  проба('Apps Script → rid-finance',
    опознать('https://script.google.com/macros/s/AKfy.../exec').проект, 'rid-finance');
  проба('VPS → помощник назначения встреч',
    опознать('https://vstrechi.example.ru/telegram/webhook').проект, 'pomoshchnik-naznacheniya-vstrech');
  проба('пустой вебхук — бота никто не обслуживает', опознать('').проект, '—');
  проба('чужой домен честно помечается неизвестным',
    опознать('https://кто-то-другой.ru/hook').проект, '❓ неизвестен');
  проба('хвост токена не утекает в вывод', безопасно('0000000000:AAAvyidumannyjhvostxxxxxxxx'), '0000000000:…');
  проба('мусор вместо токена не притворяется номером', безопасно('не-токен'), '???');
  проба('токен читается из строки вида ИМЯ=ТОКЕН',
    разобратьТокены('VIBEPOST=1234567890:AAFxxxxxxxxxxxxxxxxxxxxxxx').map(б => б.пометка), ['VIBEPOST']);
  проба('комментарии и пустые строки пропускаются',
    разобратьТокены('# коммент\n\n1234567890:AAFxxxxxxxxxxxxxxxxxxxxxxx  # старый бот').map(б => б.пометка), ['старый бот']);
  проба('повтор одного токена сверяется один раз',
    разобратьТокены('1234567890:AAFxxxxxxxxxxxxxxxxxxxxxxx\n1234567890:AAFxxxxxxxxxxxxxxxxxxxxxxx').length, 1);
  проба('короткий огрызок за токен не принимается',
    разобратьТокены('1:AAFxxxxxxxxxxxxxxxxxxxxxxx').length, 0);

  console.log(плохо ? `\nСЛОМАНО: ${плохо}\n` : '\nВся логика опознания цела.\n');
  process.exit(плохо ? 1 : 0);
}

// ── Откуда берём токены ────────────────────────────────────────────────────
const файлТокенов = join(корень, 'токены.local.txt');
let сырьё = '';
if (existsSync(файлТокенов)) {
  сырьё = readFileSync(файлТокенов, 'utf8');
} else if (existsSync(join(корень, '.env'))) {
  // Из .env берём только строки, где явно лежит токен бота.
  сырьё = readFileSync(join(корень, '.env'), 'utf8')
    .split(/\r?\n/).filter(с => /TOKEN|ТОКЕН/i.test(с)).join('\n');
}

const боты = разобратьТокены(сырьё);
if (!боты.length) {
  console.error(`
Не нашёл ни одного токена.

Создайте файл  токены.local.txt  рядом с этим проектом и впишите туда токены —
по одному на строку, можно с пометкой:

    0000000000:AAA...   vibepost, из Supabase Vault
    0000000001:BBB...   rid-finance, из Apps Script

Файл закрыт в .gitignore и в репозиторий не попадёт.
Токены смотрите: @BotFather → /mybots → выбрать бота → API Token.
`);
  process.exit(2);
}

// ── Опрос Telegram ─────────────────────────────────────────────────────────
async function спросить(токен, метод) {
  const ответ = await fetch(`https://api.telegram.org/bot${токен}/${метод}`, {
    signal: AbortSignal.timeout(15000),
  });
  const тело = await ответ.json().catch(() => ({}));
  if (!тело.ok) throw new Error(тело.description || `HTTP ${ответ.status}`);
  return тело.result;
}

console.log(`\nСВЕРКА БОТОВ — кто каким проектом управляется\n`);
console.log(`Спрашиваю у Telegram про ${боты.length} ${боты.length === 1 ? 'токен' : 'токена/токенов'}…\n`);

const строки = [];
for (const { токен, пометка } of боты) {
  const запись = { номер: безопасно(токен), пометка };
  try {
    const я = await спросить(токен, 'getMe');
    запись.имя = '@' + я.username;

    const в = await спросить(токен, 'getWebhookInfo');
    const { проект, как } = опознать(в.url);
    запись.проект = проект;
    запись.как = как;
    запись.адрес = в.url || '';
    запись.очередь = в.pending_update_count || 0;
    запись.ошибка = в.last_error_message || '';
    запись.апдейты = (в.allowed_updates || []).join(', ');
  } catch (е) {
    const текст = String(е.message || е);
    запись.имя = '—';
    // Отличать «Telegram отверг токен» от «до Telegram не дошёл запрос» —
    // обязательно. Иначе упавший интернет или прокси на работе выглядит как
    // отозванный токен, и человек идёт перевыпускать живого бота.
    if (/401|[Uu]nauthorized/.test(текст)) {
      запись.проект = '⛔ токен отозван';   // ровно это видно после /revoke
      запись.как = 'Telegram его не принимает';
    } else {
      запись.проект = '⚠ не смог проверить';
      запись.как = `${текст} — похоже на сеть или прокси, а не на токен`;
    }
  }
  строки.push(запись);
}

// ── Вывод ──────────────────────────────────────────────────────────────────
if (process.argv.includes('--markdown')) {
  console.log('| Бот | Номер | Проект | Хостинг | Очередь |');
  console.log('|---|---|---|---|---|');
  for (const с of строки) {
    console.log(`| ${с.имя} | \`${с.номер}\` | ${с.проект} | ${с.как} | ${с.очередь ?? '—'} |`);
  }
  console.log(`\n_Сверено: ${new Date().toISOString().slice(0, 10)}. Обновить: \`node scripts/сверка-ботов.mjs --markdown\`_`);
} else {
  for (const с of строки) {
    console.log(`  ${с.имя}${с.пометка ? `   (${с.пометка})` : ''}`);
    console.log(`    номер бота   ${с.номер}`);
    console.log(`    проект       ${с.проект}${с.как ? `  — ${с.как}` : ''}`);
    if (с.адрес) console.log(`    вебхук       ${с.адрес}`);
    if (с.очередь) console.log(`    ⚠ в очереди  ${с.очередь} необработанных сообщений`);
    if (с.ошибка) console.log(`    ⚠ ошибка     ${с.ошибка}`);
    if (с.апдейты) console.log(`    получает     ${с.апдейты}`);
    console.log('');
  }
}

// ── Что бросается в глаза ──────────────────────────────────────────────────
const тревоги = [];

const брошенные = строки.filter(с => с.проект === '—');
if (брошенные.length) тревоги.push(
  `${брошенные.map(с => с.имя).join(', ')} — вебхук не задан. Бота никто не обслуживает: ` +
  `либо он свободен, либо проект перестал работать и этого не заметили.`);

const чужие = строки.filter(с => с.проект.startsWith('❓'));
if (чужие.length) тревоги.push(
  `${чужие.map(с => с.имя).join(', ')} — вебхук ведёт на незнакомый адрес. ` +
  `Допишите правило в ПРАВИЛА вверху скрипта, иначе в следующий раз опять будет «неизвестен».`);

const мёртвые = строки.filter(с => с.проект.startsWith('⛔'));
if (мёртвые.length) тревоги.push(
  `${мёртвые.map(с => с.номер).join(', ')} — токен отозван. ` +
  `Если вы его отзывали сами, так и должно быть: строку можно убрать из токены.local.txt.`);

const непонятные = строки.filter(с => с.проект.startsWith('⚠'));
if (непонятные.length) тревоги.push(
  `${непонятные.map(с => с.номер).join(', ')} — до Telegram не достучались. Это НЕ значит, ` +
  `что с ботом что-то не так: проверьте интернет и повторите. Судить о боте по такому ответу нельзя.`);

// Один бот, вписанный дважды под разными токенами, — верный способ
// перебить самому себе вебхук и потом искать, почему «бот молчит».
const поИмени = new Map();
for (const с of строки) if (с.имя !== '—') поИмени.set(с.имя, (поИмени.get(с.имя) || 0) + 1);
const дубли = [...поИмени].filter(([, n]) => n > 1).map(([имя]) => имя);
if (дубли.length) тревоги.push(
  `${дубли.join(', ')} — на одного бота несколько разных токенов. Такое бывает после /revoke: ` +
  `старый где-то остался. Проверьте, каким токеном пользуется проект.`);

const застрявшие = строки.filter(с => (с.очередь || 0) > 20);
if (застрявшие.length) тревоги.push(
  `${застрявшие.map(с => `${с.имя} (${с.очередь})`).join(', ')} — сообщения копятся и не разбираются. ` +
  `Обычно это упавший обработчик на той стороне вебхука.`);

if (тревоги.length) {
  console.log('НА ЧТО ПОСМОТРЕТЬ\n');
  for (const т of тревоги) console.log(`  • ${т}\n`);
} else {
  console.log('Каждый бот привязан к своему проекту, очередей и ошибок нет.\n');
}
