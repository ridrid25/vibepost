with ov as (
  select id, scheduled_at, row_number() over (order by scheduled_at) rn
  from posts where status = $$scheduled$$ and scheduled_at < now()
), a as (
  select greatest(max(scheduled_at), now()) m from posts where status = $$scheduled$$
