// На Windows claude — это .cmd, и Node с некоторых версий отказывается
// запускать такие файлы напрямую: spawn EINVAL. Через cmd.exe /c работает,
// и предупреждения о shell тоже нет — аргументы идут отдельным массивом.
const [бинарь, префикс] = process.platform === 'win32'
  ? ['cmd.exe', ['/c', 'claude']]
  : ['claude', []];

/**
 * Замок живого дежурного.
 *
 * Приёмник теперь будит дежурного сразу, как приходит задание, — без пауз.
 * Значит лавину надо держать не временем, а фактом: пока один дежурный жив,
 * второго не поднимать. Пауза в 20 минут, стоявшая раньше, защищала от лавины
 * ценой того, что задание Татьяны лежало эти 20 минут.
 *
 * Замок пишет сам дежурный и своим номером процесса — только он его знает.
 * Приёмник запускает через wscript, и номер того запуска ничей: именно на этом
 * 8 августа замок сломался и приёмник поднял Claude 6984 раза за ночь.
 */
const замок = join(корень, 'dezhurny.pid');
try {
  process.kill(Number(readFileSync(замок, 'utf8')), 0);
  console.log('[замок] дежурный уже работает, второго не поднимаю');
  process.exit(0);
} catch { /* замка нет либо процесс из него давно умер */ }
writeFileSync(замок, String(process.pid));
const снятьЗамок = () => { try { rmSync(замок, { force: true }); } catch { /* уже нет */ } };
process.on('exit', снятьЗамок);
for (const сигнал of ['SIGINT', 'SIGTERM', 'SIGHUP']) {
  process.on(сигнал, () => { снятьЗамок(); process.exit(0); });
}

/**
 * Проверка обхода перед запуском.
 *
 * Доступ к Anthropic из России идёт через TUN-адаптер xray. Когда он опущен,
 * API отвечает «403 Request not allowed» — мгновенно и всем. Ретраи тут
 * бесполезны: 9 августа в журнале накопилось 297 таких отказов подряд, и все
 * одиннадцать часов никто об этом не узнал.
 *
 * Поэтому: не поднимать сессию вслепую. Нет обхода — сказать Татьяне словами,
 * что именно поднять, и не тратить запуск.
 */
const ПРОВЕРКА_TUN = [
  'powershell', '-NoProfile', '-Command',
  '(Get-NetAdapter | Where-Object { $_.Name -like "*tun*" -and $_.Status -eq "Up" } | Measure-Object).Count',
];

function обходПоднят() {
  try {
    const вывод = execFileSync(ПРОВЕРКА_TUN[0], ПРОВЕРКА_TUN.slice(1),
      { encoding: 'utf8', timeout: 20000 }).trim();
    return вывод !== '0';
  } catch {
    return true;   // проверить не смогли — не мешаем работать
  }
}

if (!обходПоднят()) {
  const беда = 'Не могу работать: связь с Anthropic закрыта. Поднят ли v2rayN и включён ли режим TUN? '
    + 'Без него любой мой запуск отбивается ошибкой 403, и промт написать нечем.';
  console.log('[обход опущен] ' + беда);
  try {
    execFileSync('node', [join(корень, 'scripts', 'задания.mjs'), 'сказать', беда],
      { cwd: корень, timeout: 30000 });
  } catch { /* без связи не поможешь */ }
  process.exit(0);
}

/**
 * Кнопка «Перезапустить» из бота.
 *
 * Бот ставит флаг через RPC request_worker_restart(). Долгоживущего цикла у нас
 * нет — дежурный разовый и поднимается заново каждый час, поэтому «перезапуск»
 * для него означает одно: начать с чистого листа, не таща за собой то, на чём
 * прошлый запуск застрял. Флаг снимаем сразу, чтобы он не срабатывал дважды.
 */
async function сброситьЕслиПросят() {
  try {
    const в = execFileSync('node', [join(корень, 'scripts', 'перезапуск.mjs'), 'проверить'],
      { cwd: корень, encoding: 'utf8', timeout: 30000 }).trim();
    if (в === 'ПРОСЯТ') console.log('[перезапуск] флаг снят, начинаю с чистого листа');
  } catch { /* проверка не удалась — работаем как обычно */ }
}
await сброситьЕслиПросят();

