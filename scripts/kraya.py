#!/usr/bin/env python3
"""Движение на краях ролика: первые 0,5 с (облёт на 0 с) и последние 0,7 с (крючок).

Замер (measure.py) считает среднее по всему ролику и по целым секундам, поэтому
неподвижный старт и замерший финал в нём тонут. 28.10.2026, заказчица:
«Бригада не обращает внимание на 0 сек… и крючка в конце нет». Промты их
содержат, а генератор их не играет — проверять надо готовый ролик.

Вывод: «старт <число> движется|стоит» и «финал <число> движется|замер» —
медиана разницы соседних кадров (мера как в measure.py: 12 кадров/с, ширина 240).
"""
import subprocess, sys
import numpy as np

v = sys.argv[1]
raw = subprocess.run(
    ["ffmpeg", "-hide_banner", "-loglevel", "error", "-i", v,
     "-vf", "fps=12,scale=240:426,format=gray", "-f", "rawvideo", "-"],
    check=True, capture_output=True).stdout
fr = np.frombuffer(raw, np.uint8).reshape(-1, 426, 240).astype(np.float32)
d = [float(np.abs(fr[i + 1] - fr[i]).mean()) for i in range(len(fr) - 1)]
# Склейка (разница > 45, как в measure.py) — не движение камеры: её выкидываем.
# Медиана, а не среднее: одна склейка или вспышка не должна выдавать стоящую
# камеру за полёт. Порог 6 — по кадрам 28.10: при медиане ниже 6 камера на
# старте стоит, а финал замирает (бобры с банкой — 4,9, облёт гуся — 20).
ПОРОГ = 6.0
def медиана(ряд):
    ряд = [x for x in ряд if x <= 45]
    return float(np.median(ряд)) if ряд else 0.0
старт = медиана(d[:6])     # 0,0–0,5 с
финал = медиана(d[-8:])    # последние ~0,7 с
print(f"старт {старт:5.2f} {'движется' if старт >= ПОРОГ else 'стоит'}")
print(f"финал {финал:5.2f} {'движется' if финал >= ПОРОГ else 'замер'}")
