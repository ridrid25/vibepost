/**
 * Механическая проверка промта — за секунду вместо пяти минут.
 *
 *   node scripts/промт-проверка.mjs <файл.json> ["эталонная реплика целиком"]
 *
 * Зачем. Критик тратит пять минут, и половина этого времени уходит на сверку,
 * которая мыслей не требует: посчитать слоги, найти слово «night», сложить
 * знаки, проверить окна встык. 8 августа переделка ролика на десять секунд
 * заняла час — и заказчица справедливо сказала, что это не стоит того.
 *
 * Всё, что можно посчитать, теперь считается здесь. Критика зовут после — и
 * уже только за тем, чего скрипт не умеет: смешно ли, читается ли панч,
 * крупное ли действие. Это его настоящая работа.
 *
 * Скрипт ничего не правит. Он говорит, что не так, и возвращает код 1.
 */
import { readFileSync } from 'node:fs';

const [файл, эталон] = process.argv.slice(2);
if (!файл) {
  console.error('нужен путь к json-промту');
  process.exit(2);
}

const промт = JSON.parse(readFileSync(файл, 'utf8'));
const компакт = JSON.stringify(промт);
const негатив = String(промт.negative_prompt ?? '').toLowerCase();

// Всё, кроме негатива: там запрещённые слова стоять обязаны.
const телоБезНегатива = JSON.stringify({ ...промт, negative_prompt: undefined }).toLowerCase();

const беды = [];
const заметки = [];
const плохо = (текст) => беды.push(текст);

// ── 1. Размер ─────────────────────────────────────────────────────────────
// Предел ровно 4096, а не «4096 минус теги»: проверено живой отправкой в бота —
// 4096 принимается, 4097 отклоняется. Telegram считает видимый текст, а разметку
// <pre> в него не включает. Из-за лишнего вычитания я 8 августа зря отправлял
// промт на пересборку и потом резал его по знаку в пять заходов.
const ПРЕДЕЛ = 4096;
if (компакт.length > ПРЕДЕЛ) {
  плохо(`размер ${компакт.length} знаков, предел ${ПРЕДЕЛ} — в бота одним сообщением не влезет`);
} else {
  заметки.push(`размер ${компакт.length} из ${ПРЕДЕЛ}`);
}

// ── 2. Свет: тёмная сцена — потолок динамики 12-14 при норме 18 ───────────
const ТЕМНОТА = ['night', 'dusk', 'evening', 'lamp', 'dim ', 'moody', 'low key', 'low-key', 'dark scene', 'candle', 'neon'];
const нашлась = ТЕМНОТА.filter((с) => телоБезНегатива.includes(с));
if (нашлась.length) {
  плохо(`сцена тянет в темноту: ${нашлась.join(', ')} — потолок замера 12-14 при норме 18`);
}
for (const с of ['night', 'dark scene']) {
  if (!негатив.includes(с)) заметки.push(`в негативе нет «${с}»`);
}

// ── 3. Просьба говорить быстро — модель слушается приказа, а не таймингов ──
const СПЕШКА = ['fast', 'quick', 'rapid', 'hurried', 'clipped'];
const спешит = СПЕШКА.filter((с) => телоБезНегатива.includes(с));
if (спешит.length) плохо(`просьба говорить быстро: ${спешит.join(', ')} — темп поднимаем в постобработке`);

// ── 4. Окна таймлайна: встык, без дыр и нахлёстов ─────────────────────────
const биты = Array.isArray(промт.timeline) ? промт.timeline : [];
if (!биты.length) плохо('нет таймлайна');
let конецПрошлого = 0;
const окна = [];
for (const бит of биты) {
  const m = String(бит.t ?? '').match(/^([\d.]+)\s*-\s*([\d.]+)$/);
  if (!m) { плохо(`окно «${бит.t}» не читается`); continue; }
  const [от, до] = [Number(m[1]), Number(m[2])];
  if (до <= от) плохо(`окно ${бит.t} нулевой или обратной длины`);
  const зазор = +(от - конецПрошлого).toFixed(2);
  if (Math.abs(зазор) > 0.001) {
    плохо(зазор > 0 ? `дыра ${зазор} с перед ${бит.t}` : `нахлёст ${-зазор} с на ${бит.t}`);
  }
  конецПрошлого = до;
  окна.push({ от, до, бит });
}
const длина = Number(промт.duration_seconds ?? 0);
if (длина && Math.abs(конецПрошлого - длина) > 0.001) {
  плохо(`таймлайн кончается на ${конецПрошлого}, а клип ${длина} с`);
}

// ── 5. Слоги в секунду: норма 4-5, выше — бит невыполним ──────────────────
// Невыполнимый бит ломает ПРЕДЫДУЩУЮ фразу: модель торопится заранее.
const слоги = (s) => (s.match(/[аеёиоуыэюяАЕЁИОУЫЭЮЯ]/g) ?? []).length;
const речевые = окна.filter((о) => о.бит.line);
for (const [i, о] of речевые.entries()) {
  const н = слоги(о.бит.line);
  const темп = н / (о.до - о.от);
  const метка = `${о.бит.t} «${о.бит.line}» ${н} слогов = ${темп.toFixed(2)} сл/с`;
  if (темп > 5) {
    плохо(`${метка} — невыполнимо${i > 0 ? `, сломает предыдущий бит ${речевые[i - 1].бит.t}` : ''}`);
  } else if (темп < 2.5) {
    заметки.push(`${метка} — очень медленно, проверьте что так задумано`);
  } else {
    заметки.push(метка);
  }
}

// ── 6. Реплика заказчицы: посимвольно, менять нельзя ни знака ─────────────
const склейка = речевые.map((о) => о.бит.line).join(' ');
if (эталон) {
  const норм = (s) => s.replace(/\s+/g, ' ').trim();
  if (норм(склейка) !== норм(эталон)) {
    плохо('реплика не совпадает с эталоном');
    console.error(`\n  в промте: ${склейка}\n  эталон:   ${эталон}\n`);
  } else {
    заметки.push('реплика совпадает с эталоном посимвольно');
  }
} else {
  заметки.push(`реплика (эталон не передан): ${склейка}`);
}

// ── 7. Негатив против того, что нужно в кадре ─────────────────────────────
// Запрет исполняется жёстче пояснения: если нужное попало в негатив, оно
// исчезнет из кадра, сколько его ни описывай.
const нужное = String(промт.must_appear ?? '').toLowerCase();
if (нужное) {
  // Общие слова вроде frame, light, water встречаются и там и там, но означают
  // разное: «slot light is practical» и «moody lighting» не спорят. Кричать на
  // них — значит приучить пропускать предупреждения мимо глаз.
  const ОБЩИЕ = new Set(['despite', 'negatives', 'required', 'their', 'front', 'there',
    'frame', 'light', 'lights', 'lighting', 'water', 'under', 'across', 'whole', 'still',
    'visible', 'without', 'other', 'never', 'always', 'about', 'thick', 'sharp', 'clean',
    'object', 'objects', 'props', 'scene', 'subject', 'sixth', 'touched', 'merged']);
  // А эти спорят почти всегда: именно на них трижды пропадал панч.
  const ОПАСНЫЕ = ['shadow', 'second', 'duplicate', 'insect', 'hand', 'copy', 'sack', 'dust'];
  // Запрет с оговоркой — не конфликт. «dust sparkling under red light» и
  // «thick dust is the subject» уживаются: запрещена не пыль, а её блеск при
  // красном свете. Спорит только голый запрет: «second insect», «duplicate props».
  const пункты = негатив.split(',').map((п) => п.trim()).filter(Boolean);
  const голыйЗапрет = (слово) => пункты.some((п) => {
    if (!п.includes(слово)) return false;
    if (п.startsWith('only ')) return false;            // «only its shadow» — это разрешение
    const токены = п.split(/\s+/).filter((т) => !['a', 'an', 'the', 'any', 'no'].includes(т));
    if (токены.length > 2) return false;                // «a third sack on him» — с оговоркой
    return !токены.some((т) => /(ing|ed)$/.test(т));    // «sack bursting» — запрещено действие
  });
  const слова = [...new Set(нужное.match(/[a-z]{4,}/g) ?? [])].filter((с) => !ОБЩИЕ.has(с));
  const конфликт = слова.filter(голыйЗапрет);
  const серьёзные = конфликт.filter((с) => ОПАСНЫЕ.includes(с));
  if (серьёзные.length) плохо(`в негативе стоит то, что нужно в кадре: ${серьёзные.join(', ')}`);
  const остальные = конфликт.filter((с) => !ОПАСНЫЕ.includes(с));
  if (остальные.length) заметки.push(`есть и в нужном, и в негативе — проверьте смысл: ${остальные.join(', ')}`);
}

// ── 8. Буквы в кадре: кириллица выходит мусором, заголовок вешаем сами ────
for (const с of ['subtitles', 'watermark']) {
  if (!негатив.includes(с)) заметки.push(`в негативе нет «${с}»`);
}

// ── 9. Несколько тактов в одной записи — модель исполнит первый и последний ─
for (const о of окна) {
  const действие = String(о.бит.a ?? '');
  const тактов = (действие.match(/;|\bthen\b/g) ?? []).length;
  if (тактов >= 3) {
    заметки.push(`${о.бит.t}: ${тактов + 1} тактов в одной записи — проверьте, влезут ли`);
  }
}

// ── Итог ──────────────────────────────────────────────────────────────────
console.log('\nЧТО СОШЛОСЬ');
for (const з of заметки) console.log('  ·', з);

if (беды.length) {
  console.log('\nЧТО НЕ ТАК');
  for (const б of беды) console.log('  ✗', б);
  console.log(`\nНЕ ГОДЕН: ${беды.length}. Правьте и прогоните снова.\n`);
  process.exit(1);
}
console.log('\nМеханика чистая. Дальше критик — за тем, что не считается: крупное ли действие, читается ли панч.\n');
