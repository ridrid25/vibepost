/**
 * Механическая проверка промта — за секунду вместо пяти минут.
 *
 *   node scripts/промт-проверка.mjs <файл.json> ["эталонная реплика целиком"]
 *
 * Зачем. Критик тратит пять минут, и половина этого времени уходит на сверку,
 * которая мыслей не требует: посчитать слоги, найти слово «night», сложить
 * знаки, проверить окна встык. 8 августа переделка ролика на десять секунд
 * заняла час — и заказчица справедливо сказала, что это не стоит того.
 *
 * Всё, что можно посчитать, теперь считается здесь. Критика зовут после — и
 * уже только за тем, чего скрипт не умеет: смешно ли, читается ли панч,
 * крупное ли действие. Это его настоящая работа.
 *
 * Скрипт ничего не правит. Он говорит, что не так, и возвращает код 1.
 */
import { readFileSync } from 'node:fs';

const [файл, эталон] = process.argv.slice(2);
if (!файл) {
  console.error('нужен путь к json-промту');
  process.exit(2);
}

const промт = JSON.parse(readFileSync(файл, 'utf8'));
const компакт = JSON.stringify(промт);
const негатив = String(промт.negative_prompt ?? '').toLowerCase();

// Всё, кроме негатива: там запрещённые слова стоять обязаны.
const телоБезНегатива = JSON.stringify({ ...промт, negative_prompt: undefined }).toLowerCase();

const беды = [];
const заметки = [];
const плохо = (текст) => беды.push(текст);

// ── 1. Размер ─────────────────────────────────────────────────────────────
// Предел ровно 4096, а не «4096 минус теги»: проверено живой отправкой в бота —
// 4096 принимается, 4097 отклоняется. Telegram считает видимый текст, а разметку
// <pre> в него не включает. Из-за лишнего вычитания я 8 августа зря отправлял
// промт на пересборку и потом резал его по знаку в пять заходов.
//
// Но 4096 - это ВСЁ сообщение, а промт уходит с подписью-именем персонажа
// на отдельной строке («ПАВЛИНА» и перевод строки). 23.08 счётчик написал
// «4090 из 4096», а Telegram ответил «message is too long»: 4090 + 7 знаков
// подписи = 4097. Подпись бывает длиннее, держим под неё запас.
const ПОДПИСЬ = 16;
const ПРЕДЕЛ = 4096 - ПОДПИСЬ;
if (компакт.length > ПРЕДЕЛ) {
  плохо(`размер ${компакт.length} знаков, предел ${ПРЕДЕЛ} (4096 минус подпись) — в бота одним сообщением не влезет`);
} else {
  заметки.push(`размер ${компакт.length} из ${ПРЕДЕЛ}`);
}

// ── 2. Свет: тёмная сцена — потолок динамики 12-14 при норме 18 ───────────
const ТЕМНОТА = ['night', 'dusk', 'evening', 'lamp', 'dim ', 'moody', 'low key', 'low-key', 'dark scene', 'candle', 'neon'];
const нашлась = ТЕМНОТА.filter((с) => телоБезНегатива.includes(с));
if (нашлась.length) {
  плохо(`сцена тянет в темноту: ${нашлась.join(', ')} — потолок замера 12-14 при норме 18`);
}
for (const с of ['night', 'dark scene']) {
  if (!негатив.includes(с)) заметки.push(`в негативе нет «${с}»`);
}

// ── 3. Просьба говорить быстро — модель слушается приказа, а не таймингов ──
// Сравниваем по списку слов, а не подстрокой и не регуляркой: «unhurried» —
// это просьба НЕ спешить, а поиск подстроки видел в нём «hurried» и браковал
// промт за обратное. Регулярку с границей слова тут дважды съело экранирование,
// поэтому просто режем текст на слова — ошибиться негде.
const СПЕШКА = new Set(['fast', 'quick', 'quickly', 'rapid', 'rapidly', 'hurried', 'clipped']);
// Отрицание меняет смысл на обратный: «never hurried» — это просьба НЕ спешить.
// Счётчик дважды браковал промт за слово, стоявшее под запретом.
const ОТРИЦАНИЯ = new Set(['never', 'not', 'no', 'without', 'nothing']);
const токены = телоБезНегатива.split(/[^a-zа-яё]+/i).filter(Boolean);
const спешит = [...new Set(токены.filter((т, i) =>
  СПЕШКА.has(т) && !ОТРИЦАНИЯ.has(токены[i - 1] ?? '')))];
if (спешит.length) плохо(`просьба говорить быстро: ${спешит.join(', ')} — темп поднимаем в постобработке`);

// ── 4. Окна таймлайна: встык, без дыр и нахлёстов ─────────────────────────
const биты = Array.isArray(промт.timeline) ? промт.timeline : [];
if (!биты.length) плохо('нет таймлайна');
let конецПрошлого = 0;
const окна = [];
for (const бит of биты) {
  const m = String(бит.t ?? '').match(/^([\d.]+)\s*-\s*([\d.]+)$/);
  if (!m) { плохо(`окно «${бит.t}» не читается`); continue; }
  const [от, до] = [Number(m[1]), Number(m[2])];
  if (до <= от) плохо(`окно ${бит.t} нулевой или обратной длины`);
  const зазор = +(от - конецПрошлого).toFixed(2);
  if (Math.abs(зазор) > 0.001) {
    плохо(зазор > 0 ? `дыра ${зазор} с перед ${бит.t}` : `нахлёст ${-зазор} с на ${бит.t}`);
  }
  конецПрошлого = до;
  окна.push({ от, до, бит });
}
// ── 4а. Длина битов: первый короткий, ни один не тянется ────────────────
// 12.10.2026: в 13 промтах из 15 первый бит шёл 1.45–2.90 с — одно действие на
// первые две-три секунды, а модель рисует такой бит почти неподвижным. На YouTube
// пробная группа решает «листать или нет» именно в эти секунды. Правило было
// записано словами, но его никто не мерил — теперь мерим.
const ПЕРВЫЙ_БИТ = 0.8, ЛЮБОЙ_БИТ = 1.5;
if (окна.length) {
  const первый = окна[0];
  const д = +(первый.до - первый.от).toFixed(2);
  if (д > ПЕРВЫЙ_БИТ + 0.001) {
    плохо(`первый бит ${первый.бит.t} длится ${д} с — больше ${ПЕРВЫЙ_БИТ} с: начало выйдет неподвижным, режьте на два действия`);
  } else {
    заметки.push(`первый бит ${первый.бит.t}: ${д} с`);
  }
}
// 25.10.2026: речевой бит с длинной неделимой фразой («Подушка безопасности.» —
// 8 слогов) не помещается в 1,5 с при темпе ниже 5 сл/с, а делить фразу нельзя —
// генератор вставляет слово. Такому биту разрешено ровно столько, сколько нужно
// фразе при 4,8 сл/с, но не больше 1,8 с.
const слогиБита = (s) => (String(s ?? '').match(/[аеёиоуыэюяАЕЁИОУЫЭЮЯ]/g) ?? []).length;
for (const о of окна) {
  const д = +(о.до - о.от).toFixed(2);
  const предел = о.бит.line ? Math.min(1.8, Math.max(ЛЮБОЙ_БИТ, слогиБита(о.бит.line) / 4.8)) : ЛЮБОЙ_БИТ;
  if (д > предел + 0.001) плохо(`бит ${о.бит.t} длится ${д} с — больше ${+предел.toFixed(2)} с: длинный бит рисуется статично, режьте`);
}
const длина = Number(промт.duration_seconds ?? 0);
// Заказчица 25.10.2026: «Только 10 секунд везде» — и во Flow, и в Gemini.
if (длина !== 10) плохо(`duration_seconds = ${длина || 'не задано'} — ролик всегда 10 секунд (правило 65)`);
if (длина && Math.abs(конецПрошлого - длина) > 0.001) {
  плохо(`таймлайн кончается на ${конецПрошлого}, а клип ${длина} с`);
}

// ── 5. Слоги в секунду: норма 4-5, выше — бит невыполним ──────────────────
// Невыполнимый бит ломает ПРЕДЫДУЩУЮ фразу: модель торопится заранее.
const слоги = (s) => (s.match(/[аеёиоуыэюяАЕЁИОУЫЭЮЯ]/g) ?? []).length;
const речевые = окна.filter((о) => о.бит.line);
for (const [i, о] of речевые.entries()) {
  const н = слоги(о.бит.line);
  const темп = н / (о.до - о.от);
  const метка = `${о.бит.t} «${о.бит.line}» ${н} слогов = ${темп.toFixed(2)} сл/с`;
  if (темп > 5) {
    плохо(`${метка} — невыполнимо${i > 0 ? `, сломает предыдущий бит ${речевые[i - 1].бит.t}` : ''}`);
  } else if (темп < 2.5) {
    заметки.push(`${метка} — очень медленно, проверьте что так задумано`);
  } else {
    заметки.push(метка);
  }
}

// ── 6. Реплика заказчицы: посимвольно, менять нельзя ни знака ─────────────
const склейка = речевые.map((о) => о.бит.line).join(' ');
if (эталон) {
  const норм = (s) => s.replace(/\s+/g, ' ').trim();
  if (норм(склейка) !== норм(эталон)) {
    плохо('реплика не совпадает с эталоном');
    console.error(`\n  в промте: ${склейка}\n  эталон:   ${эталон}\n`);
  } else {
    заметки.push('реплика совпадает с эталоном посимвольно');
  }
} else {
  заметки.push(`реплика (эталон не передан): ${склейка}`);
}

// ── 7. Негатив против того, что нужно в кадре ─────────────────────────────
// Запрет исполняется жёстче пояснения: если нужное попало в негатив, оно
// исчезнет из кадра, сколько его ни описывай.
const нужное = String(промт.must_appear ?? '').toLowerCase();
if (нужное) {
  // Общие слова вроде frame, light, water встречаются и там и там, но означают
  // разное: «slot light is practical» и «moody lighting» не спорят. Кричать на
  // них — значит приучить пропускать предупреждения мимо глаз.
  const ОБЩИЕ = new Set(['despite', 'negatives', 'required', 'their', 'front', 'there',
    'frame', 'light', 'lights', 'lighting', 'water', 'under', 'across', 'whole', 'still',
    'visible', 'without', 'other', 'never', 'always', 'about', 'thick', 'sharp', 'clean',
    'object', 'objects', 'props', 'scene', 'subject', 'sixth', 'touched', 'merged']);
  // А эти спорят почти всегда: именно на них трижды пропадал панч.
  const ОПАСНЫЕ = ['shadow', 'second', 'duplicate', 'insect', 'hand', 'copy', 'sack', 'dust'];
  // Запрет с оговоркой — не конфликт. «dust sparkling under red light» и
  // «thick dust is the subject» уживаются: запрещена не пыль, а её блеск при
  // красном свете. Спорит только голый запрет: «second insect», «duplicate props».
  const пункты = негатив.split(',').map((п) => п.trim()).filter(Boolean);
  const голыйЗапрет = (слово) => пункты.some((п) => {
    if (!п.includes(слово)) return false;
    if (п.startsWith('only ')) return false;            // «only its shadow» — это разрешение
    const токены = п.split(/\s+/).filter((т) => !['a', 'an', 'the', 'any', 'no'].includes(т));
    if (токены.length > 2) return false;                // «a third sack on him» — с оговоркой
    return !токены.some((т) => /(ing|ed)$/.test(т));    // «sack bursting» — запрещено действие
  });
  const слова = [...new Set(нужное.match(/[a-z]{4,}/g) ?? [])].filter((с) => !ОБЩИЕ.has(с));
  const конфликт = слова.filter(голыйЗапрет);
  const серьёзные = конфликт.filter((с) => ОПАСНЫЕ.includes(с));
  if (серьёзные.length) плохо(`в негативе стоит то, что нужно в кадре: ${серьёзные.join(', ')}`);
  const остальные = конфликт.filter((с) => !ОПАСНЫЕ.includes(с));
  if (остальные.length) заметки.push(`есть и в нужном, и в негативе — проверьте смысл: ${остальные.join(', ')}`);
}

// ── 8. Буквы в кадре: кириллица выходит мусором, заголовок вешаем сами ────
for (const с of ['subtitles', 'watermark']) {
  if (!негатив.includes(с)) заметки.push(`в негативе нет «${с}»`);
}

// ── 9. Несколько тактов в одной записи — модель исполнит первый и последний ─
for (const о of окна) {
  const действие = String(о.бит.a ?? '');
  const тактов = (действие.match(/;|\bthen\b/g) ?? []).length;
  if (тактов >= 3) {
    заметки.push(`${о.бит.t}: ${тактов + 1} тактов в одной записи — проверьте, влезут ли`);
  }
}

// ── 10. Запреты, которые душат саму динамику ──────────────────────────────
// 9 августа поросёнок дал 8.69 при норме 18 на ярком дневном свету. Причина
// нашлась в его же негативе: «camera moves besides the single push-in» и
// «new gesture inside either speech beat». Промт запрещал камере двигаться, а
// герою — что-либо делать во время речи. Оставалось стоять столбом и шевелить
// ртом. Такие формулировки пишутся из лучших побуждений и стоят целой генерации.
// Внимание к стороне: «static camera» В НЕГАТИВЕ означает «статичная камера
// запрещена» — то есть камера обязана двигаться, и это правильно. Плохо
// обратное: такие слова в теле промта либо прямой запрет двигаться в негативе.
const ДУШИТ_В_НЕГАТИВЕ = [
  ['camera moves', 'запрещено движение камеры'],
  ['camera movement', 'запрещено движение камеры'],
  ['camera motion', 'запрещено движение камеры'],
  ['moving camera', 'запрещено движение камеры'],
  ['new gesture', 'герою запрещено действовать во время речи'],
  ['gesture inside', 'герою запрещено действовать во время речи'],
];
for (const [слово, чем] of ДУШИТ_В_НЕГАТИВЕ) {
  if (негатив.includes(слово)) {
    плохо(`негатив душит динамику: «${слово}» — ${чем}. Лучшие ролики серии сняты наоборот`);
  }
}

const ДУШИТ_В_ТЕЛЕ = ['locked off', 'locked-off', 'static shot', 'static camera', 'camera locked'];
for (const слово of ДУШИТ_В_ТЕЛЕ) {
  if (телоБезНегатива.includes(слово)) {
    плохо(`камера заявлена неподвижной: «${слово}» — это потолок замера около 11`);
  }
}

// Камера должна быть заявлена как подвижная хоть где-то.
const движение = ['camera always moving', 'shot size', 'pushes in', 'camera_moves', 'lens_passes'];
if (!движение.some((с) => телоБезНегатива.includes(с.toLowerCase()))) {
  заметки.push('нигде не сказано, что камера движется и меняет крупность — обычно это стоит 5-7 пунктов замера');
}

// ── 11. Подсказка по ударению внутри реплики читается вслух ───────────────
for (const о of речевые) {
  if (/[a-zA-Z]{3}/.test(о.бит.line)) {
    плохо(`${о.бит.t}: латиница внутри реплики «${о.бит.line}» — модель прочитает её вслух, ` +
      `подсказки выносить в отдельное поле`);
  }
}

// ── 12. Кириллица в кадре выходит мусором ─────────────────────────────────
const вКадре = JSON.stringify({ ...промт, audio: undefined, timeline: (промт.timeline ?? []).map((б) => ({ ...б, line: undefined })) });
const надписи = вКадре.match(/[«"][А-ЯЁ]{3,}[»"]/g);
if (надписи) {
  плохо(`надпись кириллицей в кадре: ${надписи.join(', ')} — модель рисует её кривыми буквами, нужна пиктограмма`);
}

// ── 13. Три крупных плана (правило 60, заказчица 18.10.2026) ──────────────
// «Крупные кадры цепляют. Это точно.» Крупно — телом в объектив, не зумом.
{
  const биты = Array.isArray(промт.timeline) ? промт.timeline : [];
  const крупно = /fill(s|ing)? (the )?(whole |entire )?frame|close[- ]?up|extreme close|big close/i;
  const оптика = /push(es|ing)? in|rack focus|focus pull|zoom/i;
  const крупные = биты.filter((б) => крупно.test(`${б?.a ?? ''} ${б?.action ?? ''} ${б?.c ?? ''} ${б?.camera ?? ''}`));
  if (крупные.length < 3) {
    беды.push(`крупных планов ${крупные.length}, нужно три (правило 60): в трёх битах лицо, морда или ` +
      `предмет заполняет кадр движением в объектив — «lunges into the lens, his muzzle filling the frame»`);
  } else {
    заметки.push(`крупные планы: ${крупные.map((б) => б.t).join(', ')}`);
  }
  for (const б of крупные) {
    if (оптика.test(`${б?.a ?? ''} ${б?.c ?? ''} ${б?.camera ?? ''}`)) {
      плохо(`${б.t}: крупный план зумом или фокусом — камера стоит, замер ноль; крупно делать движением в линзу`);
    }
  }
  const пол = String(промт.motion_rule ?? '');
  if (/half the frame/i.test(пол) && !/except|close-up|close up|fills the whole frame/i.test(пол)) {
    плохо('motion_rule требует «half the frame» в каждом бите без исключения для крупных — модель выкинет крупные планы');
  }

  // ОПЫТ камеры на 10 роликов (18.10.2026) — не брак, а сведения для критика
  const ракурсы = new Set(биты.map((б) => String(б?.c ?? б?.camera ?? '').toLowerCase().trim()).filter(Boolean));
  const передний = биты.filter((б) => /foreground|at the lens|past the lens|across the lens|in front of the lens/i
    .test(`${б?.a ?? ''} ${б?.c ?? ''}`)).length;
  const наезд = биты.some((б) => /hurls? itself|rushes? (in|at|to)|camera (dives|flies|charges) (in|at|to)/i
    .test(`${б?.a ?? ''} ${б?.c ?? ''}`));
  // Опыт закончен 25.10 — три пункта стали правилом 64.
  заметки.push(`камера: ракурсов ${ракурсы.size}, передний план в ${передний} битах, наезд броском: ${наезд ? 'есть' : 'нет'}`);
  if (ракурсы.size < 4) плохо(`разных ракурсов ${ракурсы.size}, нужно не меньше четырёх (правило 64)`);
  if (передний < 2) плохо(`передний план в ${передний} битах, нужно не меньше двух (правило 64)`);
  if (!наезд) плохо('нет наезда броском камеры («the camera hurls itself …») — правило 64');
}

// ── 14. Крючок в конце (правило 61, заказчица 25.10.2026) ─────────────────
// «Надо учить не проверять, а писать ролики с такими крючками». Все финалы до
// 25.10 были развязками: упал со стола, нырнул в нору. Последний бит — крючок:
// отдельный, без речи, помечен полем hook = loop | open | reveal.
if (окна.length) {
  const последний = окна[окна.length - 1];
  const д = +(последний.до - последний.от).toFixed(2);
  const тип = String(последний.бит.hook ?? '');
  if (!['loop', 'open', 'reveal'].includes(тип)) {
    плохо(`последний бит ${последний.бит.t} без поля "hook": "loop" | "open" | "reveal" — крючок не заявлен (правило 61)`);
  }
  if (последний.бит.line) плохо(`последний бит ${последний.бит.t} с репликой — крючок идёт без речи (правило 61)`);
  if (д < 0.6) плохо(`крючок ${последний.бит.t} длится ${д} с — меньше 0.6 с, его не увидят`);
  const речь = окна.filter((о) => о.бит.line);
  const конецРечи = речь.length ? речь[речь.length - 1].до : 0;
  if (конецРечи > 9.2 + 0.001) плохо(`последняя реплика кончается в ${конецРечи} — позже 9.2, она съест крючок`);
  if (тип) заметки.push(`крючок ${последний.бит.t}: ${тип}`);
}

// ── 15. Пять строк досмотра (правило 62, заказчица 25.10.2026) ────────────
// Сценарий сдаёт: ПЕРВАЯ СЕКУНДА, ПЕРЕСМОТР, КОММЕНТАРИЙ, ПЕРЕСЛАТЬ, ГЕРОЙ СЕРИИ.
// Они лежат рядом с промтом в <имя>.plan.txt — без файла промт не годен.
{
  const путьПлана = файл.replace(/\.json$/i, '.plan.txt');
  let план = '';
  try { план = readFileSync(путьПлана, 'utf8'); } catch { /* нет файла */ }
  if (!план) {
    плохо(`нет файла ${путьПлана.split(/[\\/]/).pop()} — строки сценариста по правилам 61–62 не сданы`);
  } else {
    for (const поле of ['КРЮЧОК', 'ПЕРВАЯ СЕКУНДА', 'ПЕРЕСМОТР', 'КОММЕНТАРИЙ', 'ПЕРЕСЛАТЬ', 'ГЕРОЙ СЕРИИ', 'КУЛЬМИНАЦИЯ', 'ВНИМАНИЕ', 'ПАНЧ']) {
      const м = план.match(new RegExp(`^\\s*${поле}\\s*:\\s*(.{${поле === 'ПАНЧ' ? 2 : 8},})$`, 'm'));
      if (!м) плохо(`в плане нет строки «${поле}:» с ответом (правило 62)`);
      else if (поле === 'КУЛЬМИНАЦИЯ' && !/\d+[.,]\d/.test(м[1])) плохо('в строке КУЛЬМИНАЦИЯ нет секунды — куда вести взгляд (правило 63)');
      else if (поле === 'ВНИМАНИЕ' && (м[1].match(/→/g) ?? []).length < 4) плохо('цепочка ВНИМАНИЕ короче пяти точек — взгляд не доведён до кульминации (правило 63)');
    }
  }
}

// ── 17. Не меньше пяти динамичных движений камеры (заказчица 25.10.2026) ──
// «Не от 1 до 5 движений, а 5 не меньше. Динамичных движений!» Движение
// засчитывается по глаголу быстрого пути в поле камеры; виды считаются отдельно,
// чтобы одно и то же движение пять раз не прошло как пять.
const ВИДЫ_ДВИЖЕНИЯ = {
    'хлёсткий перевод': /\b(whip|whips|whipping|snap|snaps|swings?)\b/,
    'рывок к цели': /\b(rush|rushes|races?|racing|charges?|lunges?|hurls?|darts?|darting|flies|flying|shoots?)\b/,
    'спуск': /\b(drops?|dropping|plunges?|dives?|diving|falls?)\b/,
    'подъём': /\b(rises?|rising|soars?|climbs?|lifts?|swoops? up)\b/,
    'облёт': /\b(orbits?|circles?|circling|arcs?|round the|around the|wheels?)\b/,
    'наезд броском': /\b(rams?|crash(es)? in|slams? in|jolts?|jolting|punch(es)? in)\b/,
    'проход сквозь': /\b(through the|threads?|skims?|skimming|weaves?)\b/,
};
const схемаДвижения = (п) => (Array.isArray(п.timeline) ? п.timeline : []).map((б) => {
  const кам = String(б?.c ?? б?.camera ?? '').toLowerCase();
  return Object.entries(ВИДЫ_ДВИЖЕНИЯ).filter(([, р]) => р.test(кам)).map(([в]) => в)[0] ?? '';
});
{
  const ВИДЫ = ВИДЫ_ДВИЖЕНИЯ;
  const биты = Array.isArray(промт.timeline) ? промт.timeline : [];
  const виды = new Set();
  let движений = 0;
  for (const б of биты) {
    const кам = String(б?.c ?? б?.camera ?? '').toLowerCase();
    const нашлось = Object.entries(ВИДЫ).filter(([, р]) => р.test(кам)).map(([в]) => в);
    if (нашлось.length) { движений++; нашлось.forEach((в) => виды.add(в)); }
  }
  if (движений < 5) плохо(`динамичных движений камеры ${движений}, нужно не меньше пяти (заказчица 25.10)`);
  if (виды.size < 3) плохо(`виды движения камеры: ${[...виды].join(', ') || 'нет'} — одно и то же движение подряд, нужно разные`);
  заметки.push(`движения камеры: ${движений}, виды: ${[...виды].join(', ')}`);
}

// ── 18. Одной схемы движения на все сюжеты нет (правило 64, 25.10.2026) ────
// «Разнообразие приёмов большое. Не должно быть одной схемы движения на все
// сценарии». Схема — порядок видов движения по битам. Сравниваем с двумя
// последними промтами папки: тот же порядок первых появлений видов или
// совпадение по битам на 70% и больше — повтор.
try {
  const { readdirSync, statSync } = await import('node:fs');
  const { dirname, join, resolve } = await import('node:path');
  const папка = dirname(resolve(файл));
  const свои = resolve(файл);
  const порядок = (сх) => [...new Set(сх.filter(Boolean))].join(' → ');
  const моя = схемаДвижения(промт);
  const прошлые = readdirSync(папка).filter((f) => f.endsWith('.json') && resolve(join(папка, f)) !== свои)
    .map((f) => ({ f, t: statSync(join(папка, f)).mtimeMs })).sort((a, b) => b.t - a.t).slice(0, 2);
  for (const { f } of прошлые) {
    let чужая;
    try { чужая = схемаДвижения(JSON.parse(readFileSync(join(папка, f), 'utf8'))); } catch { continue; }
    const n = Math.min(моя.length, чужая.length);
    const совпало = n ? моя.slice(0, n).filter((в, i) => в && в === чужая[i]).length / n : 0;
    if (порядок(моя) && порядок(моя) === порядок(чужая)) {
      плохо(`схема движения повторяет ${f}: ${порядок(моя)} — возьми другое сочетание приёмов (правило 64)`);
    } else if (совпало >= 0.7) {
      плохо(`схема движения совпадает с ${f} по битам на ${Math.round(совпало * 100)}% — смени приёмы (правило 64)`);
    }
  }
} catch { /* нет папки — нет проверки */ }

