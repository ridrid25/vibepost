-- ===== ШАГ 1. СТОРОЖ. Читает, ничего не меняет. Должен РАЗЛИЧАТЬ. =====
with recursive v(variant, start) as (
  values ('СЕЙЧАС (не тронуто)', (select next_run_at from rate_configs
                                  where id = '5a1c9ad7-77c8-4457-b417-f10fb1fa0115')),
         ('ПОСЛЕ МЕРЫ',          '2026-10-06 06:10:00+00'::timestamptz)
), step as (
  select variant, 0 n, start t from v
  union all
  select variant, n + 1, recurring_compute_next('daily', null, null, 9, 10, t)
  from step where n < 30 and t <= now() + interval '2 minutes'
)
select variant,
       count(*) filter (where t <= now() + interval '2 minutes') as dublej,
       case when count(*) filter (where t <= now() + interval '2 minutes') > 1
            then 'ПРОВАЛ: лавина дублей в её канал'
            else 'ПРОЙДЕНО: один свежий пост в срок' end as verdikt
from step group by variant order by variant;
