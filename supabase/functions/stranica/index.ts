// stranica: публичные страницы VibePost для экрана согласия Google OAuth
// (домашняя страница и политика конфиденциальности). Без них Google не даёт
// перевести приложение YouTube из «Testing» в «In production», а в «Testing»
// доступ к статистике канала истекает каждые 7 дней (16.10.2026).
//   GET /functions/v1/stranica            — о сервисе
//   GET /functions/v1/stranica?doc=privacy — политика конфиденциальности
const О_СЕРВИСЕ = `VibePost — личный сервис отложенного постинга владелицы канала «рИИдФинанс».

Сервис планирует публикации в Telegram-канале и учитывает статистику собственных роликов YouTube Shorts владелицы.
Сервис не предназначен для сторонних пользователей.

Контакт: ridsochi@gmail.com`;

const ПОЛИТИКА = `VibePost — политика конфиденциальности

1. Кто пользуется. Сервисом пользуется только его владелица (ridsochi@gmail.com) для собственного канала.
2. Какие данные. С разрешения владелицы сервис читает статистику её YouTube-канала (просмотры, досмотр, источники трафика) и данные о её роликах. Персональные данные третьих лиц не собираются.
3. Зачем. Чтобы показывать владелице, какие ролики работают лучше, и планировать публикации.
4. Где хранится. В базе сервиса (Supabase, Европа). Токены доступа хранятся в зашифрованном хранилище и не передаются третьим лицам.
5. Удаление. Доступ можно отозвать в любой момент на странице https://myaccount.google.com/permissions — после этого сервис перестаёт получать данные.
6. Использование данных Google соответствует Google API Services User Data Policy, включая требования Limited Use.

Контакт: ridsochi@gmail.com`;

Deno.serve((req) => {
  const doc = new URL(req.url).searchParams.get("doc");
  return new Response(doc === "privacy" ? ПОЛИТИКА : О_СЕРВИСЕ, {
    headers: { "Content-Type": "text/plain; charset=utf-8" },
  });
});
